/**
 * The curated set of live-tunable ROS parameters, ported from `ParameterCatalog.cs` in the
 * WPF app (itself a port of `PARAM_GROUPS`/`PARAM_TIPS` in the old dashboard templates).
 *
 * Curated, not discovered: the robot has no endpoint that lists a node's parameters, and
 * `ros2 param list` would return hundreds including QoS and use_sim_time noise. The cost is
 * that a new entry in params.yaml stays invisible here until it is added below.
 *
 * A node may own more than one group — `auto_driver` has three, because sixteen driving
 * parameters plus fourteen hill ones in one list is unreadable. Groups are therefore keyed
 * by label, never by node.
 */
export interface ParamSpec {
  name: string
  tip: string
}

export interface ParamGroup {
  node: string
  label: string
  params: ParamSpec[]
}

